"""`mdu inventory`: discover-only survey of a jurisdiction's sources (PLAN §10.1, M0.2).

Counts URLs, sizes and years per source, and estimates the share of scanned PDFs from a small
sample, before anything is downloaded at scale. The full row list (with URLs) is private: it is
written to the gitignored `pipeline/.inventory/` and uploaded to R2. Only an aggregate summary,
with no URLs or folder names, is written to `docs/inventory/` for committing (ADR 0004).
"""

from __future__ import annotations

import csv
import importlib
import io
import random
import time
from collections import Counter, defaultdict
from collections.abc import Callable
from dataclasses import asdict, dataclass, field
from datetime import UTC, date, datetime
from pathlib import Path

from pypdf import PdfReader
from pypdf.errors import PdfReadError

from mdu.core.env import REPO_ROOT
from mdu.core.http import HttpError, PoliteClient

PRIVATE_DIR = REPO_ROOT / "pipeline" / ".inventory"
SUMMARY_DIR = REPO_ROOT / "docs" / "inventory"
LOW_TEXT_CHARS = 50  # a page with less text than this needs OCR (PLAN §7 stage 3)
SAMPLE_MAX_BYTES = 15 * 1024 * 1024
SAMPLE_SEED = 20261120  # fixed, so re-runs sample the same files


@dataclass
class Row:
    source: str
    kind: str  # "document" | "page"
    url: str
    year: int | None = None
    year_estimated: bool = False
    size_bytes: int | None = None
    size_from: str | None = None  # "listing" | "head" | "download"
    status: int | None = None
    label: str = ""


@dataclass
class TextSample:
    source: str
    url: str
    pages: int
    low_text_pages: int
    size_bytes: int


@dataclass
class Survey:
    city: str
    rows: list[Row] = field(default_factory=list)
    samples: list[TextSample] = field(default_factory=list)
    notes: dict[str, list[str]] = field(default_factory=lambda: defaultdict(list))
    requests: int = 0
    started: float = field(default_factory=time.monotonic)

    def note(self, source: str, text: str) -> None:
        self.notes[source].append(text)


def text_layer(data: bytes) -> tuple[int, int]:
    """(pages, pages with less than LOW_TEXT_CHARS characters of extractable text)."""
    reader = PdfReader(io.BytesIO(data))
    low = 0
    for page in reader.pages:
        try:
            chars = len((page.extract_text() or "").strip())
        except Exception:
            chars = 0
        low += chars < LOW_TEXT_CHARS
    return len(reader.pages), low


def sample_text_layers(
    client: PoliteClient,
    survey: Survey,
    source: str,
    rows: list[Row],
    *,
    k: int,
) -> list[tuple[Row, bytes]]:
    """Download up to k random PDFs of a source and record their text layer."""
    candidates = [
        r
        for r in rows
        if r.url.lower().endswith(".pdf") and (r.size_bytes or 0) <= SAMPLE_MAX_BYTES
    ]
    picked = random.Random(SAMPLE_SEED).sample(candidates, min(k, len(candidates)))
    out = []
    for row in picked:
        try:
            resp = client.get(row.url)
        except HttpError as exc:
            survey.note(source, f"sample download failed: {type(exc).__name__}")
            continue
        if resp.status != 200:  # noqa: PLR2004
            continue
        try:
            pages, low = text_layer(resp.content)
        except PdfReadError:
            survey.note(source, "a sampled PDF could not be parsed")
            continue
        survey.samples.append(TextSample(source, row.url, pages, low, len(resp.content)))
        out.append((row, resp.content))
    return out


def run(city: str, client: PoliteClient, log: Callable[[str], None] = print) -> Survey:
    module = importlib.import_module(f"mdu.adapters.{city}.inventory")
    survey = Survey(city=city)
    module.discover(client, survey, log)
    survey.requests = client.requests_sent
    return survey


# Output


def write_private_csv(survey: Survey, day: date) -> Path:
    PRIVATE_DIR.mkdir(parents=True, exist_ok=True)
    path = PRIVATE_DIR / f"{survey.city}-{day.isoformat()}.csv"
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(Row.__dataclass_fields__))
        writer.writeheader()
        for row in survey.rows:
            writer.writerow(asdict(row))
    return path


def _mb(n: float) -> str:
    return f"{n / 2**20:,.1f} MB" if n < 2**30 else f"{n / 2**30:,.2f} GB"


def summary_markdown(survey: Survey, day: date) -> str:
    """Aggregates only: no URLs, labels or folder names (they can contain personal names)."""
    by_source: dict[str, list[Row]] = defaultdict(list)
    for r in survey.rows:
        by_source[r.source].append(r)
    minutes = (time.monotonic() - survey.started) / 60

    lines = [
        f"# Inventory: {survey.city}, {day.isoformat()}",
        "",
        "Generated by `uv run mdu inventory --city "
        f"{survey.city}` (M0.2). Discover-only: listings and HEAD requests, plus a small random "
        "sample of PDFs to estimate how many need OCR. Aggregates only; the full URL list is "
        "private (R2 `inventory/`), because URLs can contain personal names.",
        "",
        f"Requests: {survey.requests} in {minutes:.0f} min "
        f"(one per 2.5 s per host, robots.txt respected).",
        "",
        "## Sources",
        "",
        "| Source | Documents | Pages (HTML) | Known size | Size known for | Years |",
        "| --- | ---: | ---: | ---: | ---: | --- |",
    ]
    for source in sorted(by_source):
        rows = by_source[source]
        docs = [r for r in rows if r.kind == "document"]
        pages = [r for r in rows if r.kind == "page"]
        sized = [r for r in docs if r.size_bytes]
        years = Counter(r.year for r in rows if r.year)
        estimated = any(r.year_estimated for r in rows)
        span = f"{min(years)}–{max(years)}" if years else "unknown"
        if estimated:
            span += " (partly estimated)"
        size = _mb(sum(r.size_bytes or 0 for r in sized))
        lines.append(
            f"| {source} | {len(docs)} | {len(pages)} | {size}"
            f" | {len(sized)}/{len(docs)} | {span} |"
        )

    lines += ["", "## Documents per year", ""]
    years_all = sorted({r.year for r in survey.rows if r.year})
    if years_all:
        lines.append("| Source | " + " | ".join(str(y) for y in years_all) + " |")
        lines.append("| --- |" + " ---: |" * len(years_all))
        for source in sorted(by_source):
            c = Counter(r.year for r in by_source[source] if r.kind == "document" and r.year)
            if c:
                lines.append(
                    f"| {source} | " + " | ".join(str(c.get(y, 0)) for y in years_all) + " |"
                )

    lines += [
        "",
        "## Scanned PDFs (sample)",
        "",
        "| Source | PDFs sampled | Pages | Pages needing OCR | Share | Avg KB/page |",
        "| --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    by_sample: dict[str, list[TextSample]] = defaultdict(list)
    for s in survey.samples:
        by_sample[s.source].append(s)
    for source in sorted(by_sample):
        ss = by_sample[source]
        page_count = sum(s.pages for s in ss)
        low = sum(s.low_text_pages for s in ss)
        kb_page = sum(s.size_bytes for s in ss) / max(1, page_count) / 1024
        share = low / max(1, page_count)
        lines.append(
            f"| {source} | {len(ss)} | {page_count} | {low} | {share:.0%} | {kb_page:,.0f} |"
        )

    lines += ["", "## Notes", ""]
    for source in sorted(survey.notes):
        for text in survey.notes[source]:
            lines.append(f"- **{source}:** {text}")
    lines.append("")
    return "\n".join(lines)


def write_outputs(survey: Survey, upload: Callable[[str, bytes], None] | None) -> tuple[Path, Path]:
    day = datetime.now(UTC).date()
    private = write_private_csv(survey, day)
    if upload:
        upload(f"inventory/{survey.city}/{private.name}", private.read_bytes())
    SUMMARY_DIR.mkdir(parents=True, exist_ok=True)
    summary = SUMMARY_DIR / f"{survey.city}-{day.isoformat()}.md"
    summary.write_text(summary_markdown(survey, day), encoding="utf-8")
    return private, summary
